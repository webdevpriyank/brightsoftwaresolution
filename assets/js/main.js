/* ==========================================================================
   Bright Software Solution — interactions
   Vanilla JS, no dependencies.
   ========================================================================== */
(function () {
  'use strict';

  var doc = document.documentElement;
  var reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  var finePointer = window.matchMedia('(hover: hover) and (pointer: fine)').matches;
  var $ = function (s, c) { return (c || document).querySelector(s); };
  var $$ = function (s, c) { return Array.prototype.slice.call((c || document).querySelectorAll(s)); };
  var lerp = function (a, b, t) { return a + (b - a) * t; };
  var clamp = function (v, a, b) { return Math.min(b, Math.max(a, v)); };
  var isRTL = function () { return doc.dir === 'rtl'; };

  /* ---------------- Preloader ---------------- */
  function finishLoad() {
    doc.classList.add('is-loaded');
    try { sessionStorage.setItem('bright-seen', '1'); } catch (e) {}
  }
  if (doc.classList.contains('no-preload') || reduceMotion) {
    requestAnimationFrame(function () { requestAnimationFrame(finishLoad); });
  } else {
    var started = Date.now();
    var done = function () { setTimeout(finishLoad, Math.max(0, 1100 - (Date.now() - started))); };
    if (document.readyState === 'complete') done(); else window.addEventListener('load', done);
    setTimeout(finishLoad, 3500); // safety net
  }

  /* ---------------- Language ----------------
     Each language is a pre-rendered page (/ and /ar/, generated by build/build.mjs) so search
     engines and AI crawlers can index both. BRIGHT_I18N is loaded on Arabic pages only, for runtime strings. */
  var dict = window.BRIGHT_I18N || {};
  function initLayout() {
    splitScrub();
    buildMarquee();
    layoutProcess();
    onScroll();
  }

  /* ---------------- Word split for scroll-scrubbed headings ---------------- */
  var scrubEls = [];
  function splitScrub() {
    scrubEls = $$('[data-scrub]');
    scrubEls.forEach(function (el) {
      // Wrap each word of text nodes in .w spans (preserve inner elements)
      var walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT, null);
      var texts = []; var n;
      while ((n = walker.nextNode())) texts.push(n);
      texts.forEach(function (t) {
        if (t.parentNode.classList && t.parentNode.classList.contains('w')) return;
        var frag = document.createDocumentFragment();
        t.textContent.split(/(\s+)/).forEach(function (part) {
          if (!part) return;
          if (/^\s+$/.test(part)) { frag.appendChild(document.createTextNode(part)); return; }
          var s = document.createElement('span'); s.className = 'w'; s.textContent = part; frag.appendChild(s);
        });
        t.parentNode.replaceChild(frag, t);
      });
      el.__words = $$('.w', el);
    });
  }

  /* ---------------- Marquee ---------------- */
  var marquee = $('[data-marquee]');
  var mqX = 0, mqW = 0, mqBoost = 0;
  function buildMarquee() {
    if (!marquee) return;
    var groups = $$('.marquee__group', marquee);
    groups.slice(1).forEach(function (g) { g.remove(); });
    var g = groups[0];
    mqW = g.offsetWidth;
    var copies = Math.ceil((window.innerWidth * 2) / Math.max(mqW, 1)) + 1;
    for (var i = 0; i < copies; i++) {
      var c = g.cloneNode(true);
      $$('[data-i18n]', c).forEach(function (e) { e.removeAttribute('data-i18n'); });
      marquee.appendChild(c);
    }
  }

  /* ---------------- Nav ---------------- */
  var nav = $('#nav');
  var lastY = window.scrollY;
  var burger = $('.nav__burger');
  var menu = $('#mobile-menu');
  function setMenu(open) {
    doc.classList.toggle('menu-open', open);
    burger.setAttribute('aria-expanded', String(open));
    burger.setAttribute('aria-label', open ? 'Close menu' : 'Open menu');
    menu.setAttribute('aria-hidden', String(!open));
  }
  burger.addEventListener('click', function () { setMenu(!doc.classList.contains('menu-open')); });
  $$('a', menu).forEach(function (a) { a.addEventListener('click', function () { setMenu(false); }); });
  document.addEventListener('keydown', function (e) { if (e.key === 'Escape') setMenu(false); });

  // Active section highlight
  var navLinks = $$('.nav__links a');
  if ('IntersectionObserver' in window) {
    var secObs = new IntersectionObserver(function (entries) {
      entries.forEach(function (en) {
        if (!en.isIntersecting) return;
        navLinks.forEach(function (a) { a.classList.toggle('is-active', a.getAttribute('href') === '#' + en.target.id); });
      });
    }, { rootMargin: '-45% 0px -50% 0px' });
    ['whatsapp', 'about', 'services', 'process', 'why', 'faq', 'contact'].forEach(function (id) { var s = document.getElementById(id); if (s) secObs.observe(s); });
  }

  /* ---------------- Reveal on scroll ---------------- */
  var revealEls = $$('[data-reveal]');
  // stagger siblings
  revealEls.forEach(function (el) {
    var sibs = Array.prototype.filter.call(el.parentNode.children, function (c) { return c.hasAttribute('data-reveal'); });
    var i = sibs.indexOf(el);
    if (i > 0) el.style.setProperty('--rd', Math.min(i * 0.08, 0.5) + 's');
  });
  if ('IntersectionObserver' in window && !reduceMotion) {
    var revObs = new IntersectionObserver(function (entries) {
      entries.forEach(function (en) {
        if (en.isIntersecting) { en.target.classList.add('is-in'); revObs.unobserve(en.target); }
      });
    }, { rootMargin: '0px 0px -8% 0px', threshold: 0.08 });
    revealEls.forEach(function (el) { revObs.observe(el); });
  } else {
    revealEls.forEach(function (el) { el.classList.add('is-in'); });
  }

  /* ---------------- Counters ---------------- */
  var counters = $$('[data-count]');
  function runCount(el) {
    var target = +el.getAttribute('data-count');
    if (reduceMotion) { el.textContent = target; return; }
    var dur = 1600, t0 = performance.now();
    (function tick(now) {
      var p = clamp((now - t0) / dur, 0, 1);
      var eased = 1 - Math.pow(1 - p, 4);
      el.textContent = Math.round(target * eased);
      if (p < 1) requestAnimationFrame(tick);
    })(t0);
  }
  if ('IntersectionObserver' in window) {
    var cObs = new IntersectionObserver(function (entries) {
      entries.forEach(function (en) { if (en.isIntersecting) { runCount(en.target); cObs.unobserve(en.target); } });
    }, { threshold: 0.6 });
    counters.forEach(function (c) { cObs.observe(c); });
  } else counters.forEach(runCount);

  /* ---------------- Process: horizontal scroll ---------------- */
  var proc = $('.process');
  var procSticky = $('.process__sticky');
  var track = $('.process__track');
  var steps = $$('.step', track).filter(function (s) { return !s.classList.contains('step--end'); });
  var stepLabel = $('[data-process-step]');
  var procBar = $('.process__bar');
  var procDist = 0, procOn = false;
  function layoutProcess() {
    if (!proc) return;
    procOn = window.innerWidth > 900 && !reduceMotion;
    if (!procOn) { proc.style.height = ''; track.style.transform = ''; return; }
    procDist = Math.max(0, track.scrollWidth - window.innerWidth);
    proc.style.height = (procSticky.offsetHeight + procDist) + 'px';
  }
  function updateProcess() {
    if (!procOn) return;
    var r = proc.getBoundingClientRect();
    var p = clamp(-r.top / Math.max(procDist, 1), 0, 1);
    var x = p * procDist * (isRTL() ? 1 : -1);
    track.style.transform = 'translate3d(' + x.toFixed(1) + 'px,0,0)';
    procBar.style.setProperty('--p', p.toFixed(4));
    var idx = clamp(Math.floor(p * steps.length * 0.999), 0, steps.length - 1);
    stepLabel.textContent = ('0' + (idx + 1)).slice(-2);
    steps.forEach(function (s, i) { s.classList.toggle('is-current', i === idx); });
  }

  /* ---------------- Scroll loop ---------------- */
  var progressBar = $('.progress span');
  var commitMark = $('.commit__mark');
  var ticking = false;
  function onScroll() {
    var y = window.scrollY;
    var h = doc.scrollHeight - window.innerHeight;
    progressBar.style.transform = 'scaleX(' + (h > 0 ? y / h : 0).toFixed(4) + ')';

    // nav hide/show
    nav.classList.toggle('is-scrolled', y > 40);
    if (!doc.classList.contains('menu-open')) {
      var dy = y - lastY;
      if (y > 400 && dy > 6) nav.classList.add('is-hidden');
      else if (dy < -6 || y < 400) nav.classList.remove('is-hidden');
    }
    mqBoost += Math.abs(y - lastY) * 0.04;
    lastY = y;

    // word scrub
    var vh = window.innerHeight;
    scrubEls.forEach(function (el) {
      var r = el.getBoundingClientRect();
      if (r.bottom < -100 || r.top > vh + 100) return;
      var start = vh * 0.9, end = vh * 0.35;
      var p = clamp((start - r.top) / (start - end + r.height * 0.6), 0, 1);
      var words = el.__words || [];
      var lit = p * words.length;
      words.forEach(function (w, i) {
        var o = clamp(lit - i, 0, 1);
        w.style.setProperty('--o', (0.18 + o * 0.82).toFixed(3));
      });
    });

    if (commitMark) {
      var cr = commitMark.parentNode.getBoundingClientRect();
      commitMark.style.setProperty('--r', ((vh - cr.top) / (vh + cr.height) * 40 - 20).toFixed(2) + 'deg');
    }
    updateProcess();
    ticking = false;
  }
  window.addEventListener('scroll', function () {
    if (!ticking) { ticking = true; requestAnimationFrame(onScroll); }
  }, { passive: true });

  var resizeT;
  window.addEventListener('resize', function () {
    clearTimeout(resizeT);
    resizeT = setTimeout(function () { buildMarquee(); layoutProcess(); onScroll(); }, 150);
  });

  /* ---------------- RAF loop: marquee + cursor + hero ---------------- */
  var mouse = { x: window.innerWidth / 2, y: window.innerHeight / 2 };
  var ring = { x: mouse.x, y: mouse.y };
  var cursor = $('.cursor'), cDot = $('.cursor__dot'), cRing = $('.cursor__ring'), cLabel = $('.cursor__label');
  var hero = $('.hero'), heroMark = $('.hero-mark'), heroGlow = $('.hero__glow');
  var heroVisible = true;
  if (!hero) heroVisible = false;
  else if ('IntersectionObserver' in window) {
    new IntersectionObserver(function (e) { heroVisible = e[0].isIntersecting; }).observe(hero);
  }

  if (finePointer && !reduceMotion) {
    doc.classList.add('has-cursor');
    window.addEventListener('mousemove', function (e) { mouse.x = e.clientX; mouse.y = e.clientY; cursor.classList.remove('is-hidden'); }, { passive: true });
    document.addEventListener('mouseleave', function () { cursor.classList.add('is-hidden'); });
    document.addEventListener('mouseover', function (e) {
      var t = e.target.closest('a, button, summary, label, [data-cursor]');
      var lbl = t && t.getAttribute('data-cursor');
      cursor.classList.toggle('is-hover', !!t && !lbl);
      cursor.classList.toggle('is-label', !!lbl);
      if (lbl) cLabel.textContent = doc.lang === 'ar' && dict.ar && dict.ar['cursor.' + lbl] ? dict.ar['cursor.' + lbl] : lbl;
    });
    // text fields keep a native caret
    $$('input, textarea').forEach(function (el) {
      el.addEventListener('mouseenter', function () { cursor.classList.add('is-hidden'); });
      el.addEventListener('mouseleave', function () { cursor.classList.remove('is-hidden'); });
    });
  }

  var t0 = performance.now();
  function frame(now) {
    // marquee
    if (marquee && mqW && !reduceMotion) {
      mqBoost *= 0.92;
      mqX -= 0.6 + Math.min(mqBoost, 14);
      if (-mqX >= mqW) mqX += mqW;
      marquee.style.transform = 'translate3d(' + mqX.toFixed(2) + 'px,0,0)';
    }
    // cursor
    if (doc.classList.contains('has-cursor')) {
      ring.x = lerp(ring.x, mouse.x, 0.18); ring.y = lerp(ring.y, mouse.y, 0.18);
      cDot.style.transform = 'translate3d(' + mouse.x + 'px,' + mouse.y + 'px,0)';
      cRing.style.transform = 'translate3d(' + ring.x.toFixed(1) + 'px,' + ring.y.toFixed(1) + 'px,0)';
    }
    // hero: the dot inside the B "looks" toward the cursor
    if (heroVisible && heroMark && !reduceMotion) {
      var nx, ny;
      if (finePointer) {
        var r = heroMark.getBoundingClientRect();
        var cx = r.left + r.width * 0.21, cy = r.top + r.height * 0.76; // dot centre in mark
        var ax = mouse.x - cx, ay = mouse.y - cy, d = Math.hypot(ax, ay) || 1;
        var k = Math.min(d / 300, 1);
        nx = (ax / d) * k; ny = (ay / d) * k;
      } else {
        var t = (now - t0) / 1600;
        nx = Math.cos(t) * 0.6; ny = Math.sin(t * 1.3) * 0.6;
      }
      heroMark.style.setProperty('--dx', (nx * 34).toFixed(1) + 'px');
      heroMark.style.setProperty('--dy', (ny * 34).toFixed(1) + 'px');
      var px = (mouse.x / window.innerWidth - 0.5), py = (mouse.y / window.innerHeight - 0.5);
      if (finePointer) {
        heroMark.style.setProperty('--mx', (px * -18).toFixed(1) + 'px');
        heroMark.style.setProperty('--my', (py * -18).toFixed(1) + 'px');
        heroGlow.style.setProperty('--gx', (px * 60).toFixed(1) + 'px');
        heroGlow.style.setProperty('--gy', (py * 60).toFixed(1) + 'px');
      }
    }
    requestAnimationFrame(frame);
  }
  requestAnimationFrame(frame);

  /* ---------------- Magnetic buttons ---------------- */
  if (finePointer && !reduceMotion) {
    $$('.magnetic').forEach(function (el) {
      el.addEventListener('mousemove', function (e) {
        var r = el.getBoundingClientRect();
        var x = e.clientX - r.left - r.width / 2, y = e.clientY - r.top - r.height / 2;
        el.style.transform = 'translate(' + (x * 0.22).toFixed(1) + 'px,' + (y * 0.3).toFixed(1) + 'px)';
      });
      el.addEventListener('mouseleave', function () { el.style.transform = ''; });
    });
  }

  /* ---------------- Spotlight cards ---------------- */
  $$('.spot').forEach(function (el) {
    el.addEventListener('pointermove', function (e) {
      var r = el.getBoundingClientRect();
      el.style.setProperty('--mx', (e.clientX - r.left) + 'px');
      el.style.setProperty('--my', (e.clientY - r.top) + 'px');
    });
  });

  /* ---------------- Infra status bars + clocks ---------------- */
  $$('.status__bars').forEach(function (b) {
    var html = '';
    for (var i = 0; i < 24; i++) html += '<i' + (Math.random() < 0.04 ? ' class="dim"' : '') + ' style="height:' + (10 + Math.round(Math.random() * 8)) + 'px"></i>';
    b.innerHTML = html;
  });
  var clocks = $$('[data-clock]');
  function tickClock() {
    var s;
    try {
      s = new Intl.DateTimeFormat('en-GB', { hour: '2-digit', minute: '2-digit', hour12: false, timeZone: 'Asia/Kolkata' }).format(new Date());
    } catch (e) { s = ''; }
    clocks.forEach(function (c) { c.textContent = c.classList.contains('status__clock') ? s + ' IST' : s; });
  }
  tickClock(); setInterval(tickClock, 15000);

  /* ---------------- WhatsApp phone: looping chat demo ---------------- */
  var chat = $('[data-chat]');
  if (chat) {
    var msgs = $$('.msg', chat);
    var typing = $('.typing', chat);
    var chatTimer = null, chatVisible = false, chatRunning = false;
    var wait = function (ms) { return new Promise(function (r) { chatTimer = setTimeout(r, ms); }); };
    function showAll() { msgs.forEach(function (m) { m.classList.add('is-shown'); }); }
    function play() {
      if (chatRunning) return;
      chatRunning = true;
      var i = 0;
      chat.classList.remove('is-fading');
      msgs.forEach(function (m) { m.classList.remove('is-shown'); });
      (function next() {
        if (!chatVisible) { chatRunning = false; return; }
        if (i >= msgs.length) {
          wait(3800).then(function () {
            chat.classList.add('is-fading');
            return wait(500);
          }).then(function () { chatRunning = false; if (chatVisible) play(); });
          return;
        }
        var m = msgs[i++];
        var isOut = m.classList.contains('msg--out');
        var pre = isOut ? wait(350).then(function () { typing.classList.add('is-on'); chat.appendChild(typing); return wait(1000); }) : wait(i === 1 ? 400 : 1100);
        pre.then(function () {
          typing.classList.remove('is-on');
          m.classList.add('is-shown');
          next();
        });
      })();
    }
    if (reduceMotion || !('IntersectionObserver' in window)) showAll();
    else {
      new IntersectionObserver(function (e) {
        chatVisible = e[0].isIntersecting;
        if (chatVisible) play();
      }, { threshold: 0.35 }).observe(chat);
    }
  }

  /* ---------------- Links that preselect a form interest ---------------- */
  $$('[data-interest]').forEach(function (a) {
    a.addEventListener('click', function () {
      var box = $('#contact-form input[value="' + a.getAttribute('data-interest') + '"]');
      if (box) box.checked = true;
    });
  });

  /* ---------------- FAQ: one open at a time ---------------- */
  var faqs = $$('.faq__item');
  faqs.forEach(function (d) {
    d.addEventListener('toggle', function () {
      if (d.open) faqs.forEach(function (o) { if (o !== d) o.open = false; });
    });
  });

  /* ---------------- Contact form ---------------- */
  var form = $('#contact-form');
  if (form) {
    var status = $('.form__status', form);
    var tsField = form.querySelector('input[name="ts"]');
    tsField.value = String(Math.floor(Date.now() / 1000));
    var t = function (key, fallback) { return doc.lang === 'ar' && dict.ar && dict.ar[key] ? dict.ar[key] : fallback; };

    form.addEventListener('submit', function (e) {
      e.preventDefault();
      var ok = true;
      ['name', 'email', 'message'].forEach(function (n) {
        var f = form.elements[n];
        var bad = !f.value.trim() || (n === 'email' && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(f.value.trim()));
        f.parentNode.classList.toggle('is-invalid', bad);
        if (bad) ok = false;
      });
      if (!ok) {
        status.className = 'form__status is-err';
        status.textContent = t('form.invalid', 'Please add your name, a valid email and a short message.');
        return;
      }
      form.classList.add('is-sending');
      status.className = 'form__status';
      status.textContent = t('form.sending', 'Sending…');

      var fd = new FormData(form);
      var attr = window.BrightTrack ? window.BrightTrack.attribution() : {};
      Object.keys(attr).forEach(function (k) { if (attr[k]) fd.append('attr[' + k + ']', attr[k]); });
      fd.append('page', location.pathname);
      var interests = $$('input[name="services[]"]:checked', form).map(function (c) { return c.value; }).join(', ');

      fetch(form.action, { method: 'POST', body: fd, headers: { 'Accept': 'application/json' } })
        .then(function (r) { return r.json().catch(function () { return { ok: false }; }); })
        .then(function (res) {
          if (res && res.ok) {
            status.className = 'form__status is-ok';
            status.textContent = t('form.ok', 'Thank you! Your message is on its way — we will get back to you shortly.');
            try { sessionStorage.setItem('bright-lead', JSON.stringify({ interests: interests, lang: doc.lang })); } catch (e2) {}
            // dedicated thank-you URL = reliable conversion tracking for Google Ads / Meta / GA4
            location.href = doc.lang === 'ar' ? '/ar/thank-you/' : '/thank-you/';
          } else throw new Error(res && res.error);
        })
        .catch(function () {
          status.className = 'form__status is-err';
          status.innerHTML = t('form.err', 'Something went wrong. Please email us at <a href="mailto:info@brightsoftwaresolution.in">info@brightsoftwaresolution.in</a>.');
        })
        .then(function () { form.classList.remove('is-sending'); });
    });
    $$('input, textarea', form).forEach(function (f) {
      f.addEventListener('input', function () { f.parentNode.classList.remove('is-invalid'); });
    });
  }

  /* ---------------- Footer year ---------------- */
  $$('[data-year]').forEach(function (y) { y.textContent = new Date().getFullYear(); });

  /* ---------------- Landing pages: preselect the page's service in the form ---------------- */
  var pre = form && form.getAttribute('data-preselect');
  if (pre) { var preBox = $('input[value="' + pre + '"]', form); if (preBox) preBox.checked = true; }

  /* ---------------- Init ---------------- */
  initLayout();
  window.addEventListener('load', function () { buildMarquee(); layoutProcess(); onScroll(); });
  if (document.fonts && document.fonts.ready) document.fonts.ready.then(function () { buildMarquee(); layoutProcess(); });
})();
